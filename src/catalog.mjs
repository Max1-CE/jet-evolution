/** Межі вузла в меридіані [s0, s1, r0, r1]. */
function extentOf(node) {
  let s0 = Infinity, s1 = -Infinity, r0 = Infinity, r1 = -Infinity;
  const add = (s, r) => { s0 = Math.min(s0, s); s1 = Math.max(s1, s); r0 = Math.min(r0, r); r1 = Math.max(r1, r); };
  const walk = (n) => {
    for (const g of n.geo ?? []) {
      if (g.t === "lathe") for (const [s, r] of g.poly) add(s, r + (g.at ? Math.hypot(...g.at[0]) : 0));
      if (g.t === "blades") for (const [s, r] of g.row.poly) add(s, r);
    }
    for (const k of n.kids ?? []) walk(k);
  };
  walk(node);
  return [s0, s1, r0, r1];
}

/** Зсуви для розбирання вузла: зовнішні корпуси — вгору, внутрішні ротори — вниз, решта — розсуваються вздовж осі. */
function spreadKids(node, { gap } = {}) {
  const kids = node.kids;
  if (!kids || kids.length < 2) return node;
  const ext = kids.map(extentOf);
  const R = Math.max(...ext.map((x) => x[3]));
  const S0 = Math.min(...ext.map((x) => x[0]));
  const S1 = Math.max(...ext.map((x) => x[1]));
  const len = S1 - S0;
  const lift = r4(Math.max(0.12, 0.7 * R));
  const axial = [];
  kids.forEach((k, i) => {
    const [s0, s1, , r1] = ext[i];
    const solid = (k.geo ?? []).filter((g) => g.t === "lathe");
    if (k.role === "outer" || (solid.length && !k.kids && k.kind === "case" && r1 >= 0.93 * R)) k.ex = [0, lift, 0];
    else if (k.role === "inner" || (solid.length && !k.kids && (k.kind === "rotor" || k.kind === "shaft") && s1 - s0 > 0.55 * len && r1 < 0.8 * R)) k.ex = [0, -lift, 0];
    else axial.push(i);
  });
  axial.sort((a, b) => ext[a][0] + ext[a][1] - ext[b][0] - ext[b][1]);
  const g = gap ?? Math.max(0.08, Math.min(0.22, len / Math.max(2, axial.length) * 0.9));
  axial.forEach((i, rank) => { kids[i].ex = [r4((rank - (axial.length - 1) / 2) * g), 0, 0]; });
  return node;
}

